export function fmtCm(val) {
  const r = Math.round(val * 10) / 10;
  return r % 1 === 0 ? r.toFixed(0) : r.toFixed(1);
}

export function getSpecTitle(spec, lang = 'ro') {
  if (!spec) return '';
  if (lang === 'ru') return spec.ru || spec.name;
  if (lang === 'ro') return spec.ro || spec.name;
  return spec.name;
}

export function formatPartDimsText(dimsCm, lang = 'ro') {
  if (!dimsCm) return '';
  const dict = I18N[lang] || I18N.ro;
  const { w, h, d } = dimsCm;
  return `${dict.lblW} ${fmtCm(w)} × ${dict.lblH} ${fmtCm(h)} × ${dict.lblD} ${fmtCm(d)} cm`;
}
